ALIASES = {"法律顾问":"法务 合同 合规", "法务经理":"法务 法律 合同", "合同审查专员":"法务 法律 合同", "数据合规顾问":"法务 合规 隐私", "提示词工程师":"AI prompt 提示词", "知识库架构师":"AI 知识库 RAG"}

def seed_job_roles(db: Session) -> None:
    if db.query(JobRole).count(): return
    order = 0
    for industry, titles in GROUPS.items():
        for title in titles.split(','):
            order += 1
            common = industry == "通用"
            db.add(JobRole(industry=industry, category=industry, title=title, aliases=ALIASES.get(title, title.replace('经理','管理')), description=f"负责{title}相关工作，为业务提供专业建议与执行支持。", role_prompt_template=f"你是公司的{title}。请从{title}的专业职责出发，给出清晰、务实、可执行且注意风险的建议。", is_common=common, sort_order=order))
    db.commit()
